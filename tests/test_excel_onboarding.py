from datetime import datetime, timezone
from io import BytesIO
import hashlib

import pytest
from openpyxl import Workbook

from islandos_core.onboarding import inspect_excel_bytes, inspect_excel_sheets


NOW = datetime(2026, 11, 7, 12, 0, tzinfo=timezone.utc)


def workbook_bytes(build):
    workbook = Workbook()
    build(workbook)
    stream = BytesIO()
    workbook.save(stream)
    return stream.getvalue()


def basic_workbook(workbook):
    sheet = workbook.active
    sheet.title = "Telemetry"
    sheet.append(["Site export generated by inverter portal"])
    sheet.append(["timestamp", "Load (kW)", "PV Power (W)"])
    sheet.append([datetime(2026, 11, 7, 10), 100, 25000])
    sheet.append([datetime(2026, 11, 7, 11), 110, 30000])


def test_excel_auto_detects_header_and_preserves_original_workbook_hash():
    raw = workbook_bytes(basic_workbook)
    report = inspect_excel_bytes(
        raw, source_type="customer_provided", source_name="site.xlsx",
        timezone_name="UTC", now=NOW,
    )
    assert report["status"] == "valid"
    assert report["artifact"]["sha256"] == hashlib.sha256(raw).hexdigest()
    assert report["artifact"]["worksheet"] == "Telemetry"
    assert report["artifact"]["header_row"] == 2
    assert report["row_count"] == 2
    mappings = {item["canonical_field"]: item for item in report["column_mappings"]}
    assert mappings["pv_power_kw"]["conversion_to_canonical"] == 0.001
    assert report["preview"][0]["values"]["pv_power_kw"] == 25.0


def test_excel_naive_timestamps_require_explicit_timezone():
    raw = workbook_bytes(basic_workbook)
    report = inspect_excel_bytes(raw, source_type="measured", now=NOW)
    assert report["status"] == "invalid"
    assert "invalid_timestamp" in {issue["code"] for issue in report["issues"]}


def test_excel_rejects_ambiguous_daylight_saving_timestamp():
    def build(workbook):
        sheet = workbook.active
        sheet.append(["timestamp", "load_kw"])
        sheet.append([datetime(2026, 11, 1, 1, 30), 100])

    raw = workbook_bytes(build)
    with pytest.raises(ValueError, match="ambiguous local timestamp"):
        inspect_excel_bytes(
            raw, source_type="measured", timezone_name="America/New_York", now=NOW,
        )


def test_excel_does_not_evaluate_formula_cells():
    def build(workbook):
        sheet = workbook.active
        sheet.append(["timestamp", "load_kw"])
        sheet.append([datetime(2026, 11, 7, 10), 100])
        sheet.append([datetime(2026, 11, 7, 11), "=100+10"])

    raw = workbook_bytes(build)
    report = inspect_excel_bytes(
        raw, source_type="measured", timezone_name="UTC", now=NOW,
    )
    assert report["artifact"]["formula_cell_count"] == 1
    assert "formula_cells_present" in {issue["code"] for issue in report["issues"]}
    assert report["preview"][1]["values"]["load_kw"] is None


def test_excel_lists_hidden_sheets_and_rejects_oversized_input():
    def build(workbook):
        hidden = workbook.create_sheet("Hidden")
        hidden.sheet_state = "hidden"

    raw = workbook_bytes(build)
    sheets = inspect_excel_sheets(raw)
    assert {"name": "Hidden", "state": "hidden", "visible": False} in sheets
    with pytest.raises(ValueError, match="import limit"):
        inspect_excel_sheets(raw, max_file_bytes=10)
